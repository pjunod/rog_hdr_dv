def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def durable(path):
    path = Path(path).resolve()
    if any(path == Path(p) or Path(p) in path.parents for p in ('/tmp', '/private/tmp', '/var/tmp')):
        raise ValueError('output must be durable')
    if path.exists():
        raise ValueError('fresh output required; preserve previous work')
    return path


def verify(directory, files):
    bound = {}
    for name, (size, digest) in files.items():
        path = directory / name
        if not path.is_file():
            raise ValueError('pinned artifact missing: ' + name)
        actual = (path.stat().st_size if size is not None else None, sha(path))
        if actual != (size, digest):
            raise ValueError('pinned artifact differs: ' + name + ' ' + repr(actual))
        bound[name] = {'size': size, 'sha256': digest}
    return bound


def aggregate_patch(debian_archive):
    """Hash and header facts of the aggregate patch inside a debian archive."""
    with tarfile.open(debian_archive, 'r:xz') as packed:
        members = {m.name.removeprefix('./'): m for m in packed.getmembers()}
        data = packed.extractfile(members[AGGREGATE_PATCH]).read()
    # Everything before the first diff hunk: DEP3 fields plus any template text.
    header = data.split(b'\n--- ', 1)[0].decode(errors='replace')
    lines = header.splitlines()
    reviewed = [line for line in lines if line.startswith('Reviewed-By:')]
    for line in reviewed:
        if line.removeprefix('Reviewed-By:').strip() != TEMPLATE_REVIEWER:
            raise ValueError('aggregate patch names a reviewer; no review was given: ' + line)
    subject = next((line for line in lines if line.startswith('Subject:')), '')
    return {'member': AGGREGATE_PATCH, 'size': len(data), 'sha256': hashlib.sha256(data).hexdigest(),
            'header_sha256': hashlib.sha256(header.encode()).hexdigest(),
            'header_lines': len(lines),
            'template_subject': TEMPLATE_SUBJECT in subject,
            'template_todo': any(line.startswith('TODO:') for line in lines),
            'template_reviewed_by': bool(reviewed),
            'reviewer_named': False,
            'generated_date': next((line.removeprefix('Date:').strip() for line in lines
                                    if line.startswith('Date:')), None),
            'placeholder_lines': sum(1 for line in lines if '<' in line and '>' in line)}


def series(repository, relative):
    path = Path(repository) / relative
    entries = [line for line in path.read_text().splitlines() if line and not line.startswith('#')]
    return {'file': relative, 'sha256': sha(path), 'patches': len(entries),
            'patch_sha256_aggregate': hashlib.sha256(''.join(
                sha(path.parent / entry) for entry in entries).encode()).hexdigest()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--kit', required=True, type=Path, help='kit root with mutter/, library/, library-source/, launcher/')
    parser.add_argument('--repository', required=True, type=Path, help='checkout of the packaging repository')
    parser.add_argument('--repository-commit', required=True)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    if not re.fullmatch('[0-9a-f]{40}', args.repository_commit):
        raise ValueError('full packaging repository commit required')
    out = durable(args.output)
    kit = args.kit.resolve()
    record = {'schema': 1, 'kind': 'source-provenance-errata', 'kit': str(kit),
              'repository_commit': args.repository_commit, 'components': {}, 'errata': ERRATA,
              'reproducibility': 'normal source packaging with pinned inputs; no bit-for-bit claim',
              'review': 'REVIEW316 (t_c3e311e9) plus its focused closure; template Reviewed-By is not an approval'}
    for component, pins in PINNED.items():
        directory = kit / component
        bound = verify(directory, pins['files'])
        archive = next(name for name in pins['files'] if name.endswith('.debian.tar.xz'))
        record['components'][component] = {
            'version': pins['version'], 'canonical_commit': pins['canonical_commit'],
            'canonical_tree': pins['canonical_tree'], 'recipe_commit': pins['recipe_commit'],
            'binary_build': pins['binary_build'], 'files': bound,
            'aggregate_patch': aggregate_patch(directory / archive),
            'original_series': series(args.repository, pins['series']),
            'source_receipt_sha256': sha(directory / 'source-receipt.json')}
    retained = kit / 'library'
    record['retained_library_binaries'] = verify(retained, {name: (None, digest)
                                                            for name, digest in RETAINED_LIBRARY.items()})
    record['retained_library_disposition'] = 'original bytes, no new build; not built from library-source/'
    record['superseded_launcher'] = SUPERSEDED_LAUNCHER
    launcher = kit / 'launcher'
    current = sorted(launcher.glob('*.dsc'))
    record['current_launcher'] = {p.name: {'size': p.stat().st_size, 'sha256': sha(p)} for p in current}
    out.mkdir(parents=True)
    (out / 'SOURCE-PROVENANCE.json').write_text(json.dumps(record, indent=2) + '\n')
    lines = ['SOURCE PROVENANCE AND ERRATA — merged HDR Ubuntu kit', '',
             'Repository commit: ' + args.repository_commit, '']
    for component, facts in record['components'].items():
        lines += [component + ' ' + facts['version'],
                  '  canonical commit ' + facts['canonical_commit'] + ' tree ' + facts['canonical_tree'],
                  '  recipe commit ' + facts['recipe_commit'] + '; binary build: ' + str(facts['binary_build'])]
        for name, bound in facts['files'].items():
            lines.append('  ' + bound['sha256'] + ' ' + str(bound['size']) + ' ' + name)
        patch = facts['aggregate_patch']
        lines += ['  aggregate patch ' + patch['member'] + ' sha256 ' + patch['sha256'] + ' size ' + str(patch['size']),
                  '  template header: subject=' + str(patch['template_subject']) + ' todo=' + str(patch['template_todo'])
                  + ' reviewed-by placeholder=' + str(patch['template_reviewed_by']) + ' reviewer named=False',
                  '  original series ' + facts['original_series']['file'] + ' sha256 ' + facts['original_series']['sha256']
                  + ' (' + str(facts['original_series']['patches']) + ' patches)', '']
    lines += ['Retained hdr9 binaries (original bytes, not built from library-source/):']
    lines += ['  ' + bound['sha256'] + ' ' + name for name, bound in record['retained_library_binaries'].items()]
    lines += ['', 'Superseded launcher ' + SUPERSEDED_LAUNCHER['version'] + ' .dsc ' + SUPERSEDED_LAUNCHER['dsc_sha256'],
              '', 'ERRATA'] + ['  ' + item for item in ERRATA] + ['']
    (out / 'SOURCE-PROVENANCE.txt').write_text('\n'.join(lines))
    print(json.dumps({k: v for k, v in record.items() if k != 'errata'}, indent=2))


if __name__ == '__main__':
    main()
